const lines = csvData.trim().split('\n');
const rooms = [];

// Skip header lines (first 2 lines)
for (let i = 2; i < lines.length; i++) {
  const line = lines[i];
  if (!line.trim()) continue;
  
  const cols = line.split(',');
  const type = cols[0]?.trim();
  
  // Only process meeting rooms (type = 10)
  if (type === '10') {
    const building = cols[2]?.trim() || '';
    const floor = cols[3]?.trim() || '';
    const roomName = cols[4]?.trim() || '';
    const department = cols[5]?.trim() || '';
    const capacityStr = cols[9]?.trim() || '0';
    const capacity = parseInt(capacityStr) || 0;
    
    if (roomName) {
      rooms.push({
        name: roomName,
        description: `${department} - อาคาร ${building} ชั้น ${floor}`,
        capacity: capacity,
        amenities: 'projector,whiteboard',
        department: department
      });
    }
  }
}

// Export as JSON
